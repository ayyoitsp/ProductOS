/**
 * ⛔ A CORPUS CAN FAIL HANDOVER FOR A DOOR THAT OPENS ON NO SCREEN. THERE WAS NO REFUSAL FOR A
 * CAPABILITY THAT OPENS ON NO REVIEWER.
 *
 * The deploying session's words, and they name the shape exactly. Twice in two days:
 *
 *   · `within` — the one relation a walk is built from — existed in the schema, loaded, was checked,
 *     was rendered, and had NO WRITER AT ALL. The only way to state it was to hand-edit a truth
 *     file. The corpus it was built for sat at 0 of 17 screens placed and fifteen front doors, with
 *     the fix reachable only by typing YAML.
 *   · `splits_on` landed with a CLI command, and Peter reviews in a browser: *"again, why do you
 *     fucking need to know this? I need you to make framework changes. I should be able to drive
 *     this from the listener/input, right??? why could you possibly need this?"* An hour later
 *     `v2 inside` shipped the same way — resolved, tested, working, unreachable.
 *
 * Both times the capability was real and the person could not get to it, and nothing in the build
 * could tell. So this is the refusal: a fact a reviewer states while looking at the product must be
 * reachable from where they are standing.
 *
 * ⛔ WHY THE `document` INTENT DOES NOT COUNT. It can write any truth file from the page, so on
 * paper every field is already reachable — which would make this test a zero with no failing state,
 * the exact thing we have spent the week naming. Nobody rewrites a feature's whole truth file in a
 * textarea to say that a tab is shown inside a shell. Reachable means a targeted intent that names
 * the fact.
 *
 * ⛔ AND THE SHAPES HERE ARE THE ONES A REVIEWER OPERATES ON WHILE REVIEWING — a screen and the
 * prototypes. Not the whole model: a scope's `in` or an exchange's slots are authoring, done with a
 * session, and claiming otherwise would make this list a chore nobody believes.
 */
import assert from "node:assert/strict";
import { test } from "node:test";

const schema = await import("../dist/v2/schema.js");
const { INTENTS } = await import("../dist/v2/intents.js");

/**
 * Fields on these shapes that no reviewer sets, with the reason.
 *
 * ⛔ A NAME HERE IS A CLAIM THAT THIS IS NOT A REVIEWER'S FACT — generator output, or something only
 * an authoring session writes. It is not a way to quiet the test, and every entry has to be
 * arguable by somebody reading it.
 */
const NOT_A_REVIEWERS_FACT = new Map([
  ["id", "the handle, derived from the title where a command makes one"],
  ["title", "named when the thing is declared, which is itself an intent"],
  ["sketch", "generated — the ASCII rendering of the drawing"],
  ["sketch_html", "generated by `draw` from the component; the author's acts are the parts and the behaviours"],
  ["shows", "a claim about what a drawing demonstrates, written beside the drawing by whoever drew it"],
  ["drawn_from", "provenance, recorded by the generator"],
  ["drawn_at", "provenance, recorded by the generator"],
  ["states", "generated — one drawing per condition found in the code"],
  ["parts", "stamped into the drawing by the generator and read back; a reviewer presses them rather than typing them"],
  ["view_kind", "selectable by a Rule, not a thing somebody sets per screen"],
  ["exists", "lifecycle — moved by `withdraw`, which is an act with its own gate"],
  ["shell_html", "generated from the layouts around a route"],
  ["shell_from", "names a path in a repository, which a reviewer in a browser does not have"],
  ["nav", "generated from the product's own menu, then kept once edited — its own surface"],
  ["from", "which layout files it was drawn from; provenance"],
]);

/** Everything the page offers, as the set of field names any intent will read. */
const FIELDS_INTENTS_TAKE = new Set(INTENTS.flatMap((i) => i.takes.map((f) => f.name.toLowerCase())));

/**
 * What an intent is really offering, where the field name and the schema key differ.
 *
 * ⛔ DECLARED, NOT FUZZY-MATCHED. A test that matched `within` against `inside` by prefix would also
 * match things that have nothing to do with each other and would quietly go green on the next
 * rename. Each line here says "this intent field sets that schema field", and is wrong in a way
 * somebody can see.
 */
const REACHED_BY = new Map([
  ["within", "inside"],
  ["is", "prototype"],
  ["starts_at", "prototype"],
  ["splits_on", "splits-on"],
  /**
   * ⛔ THE LIST ITSELF, EDITED ONE MEMBER AT A TIME. `prototype` declares one, changes one, and
   * takes one back — which is how a list is edited from a page. The removal did not exist until
   * this test's first run said so: declaring without removing is a one-way door, and somebody who
   * added a prototype by mistake from a browser had no route back at all.
   */
  ["prototypes", "prototype"],
  /**
   * ⛔ WHO A SCREEN IS FOR, AND THE WAY BACK. Peter: *"we need dimensions to carry through to all
   * features, so we can have different variations PER feature"*.
   *
   * This test is what made the intent exist: the field was added, the renderer showed it, the checker
   * refused a typo in it — and the only way to SET it was to hand-edit a document, which is the
   * hand-authoring trap this project opens on. `holds-for` with an empty combination takes it back,
   * for the reason the note above gives about one-way doors.
   */
  ["holds_for", "holds-for"],
]);

const shapeOf = (name) => {
  const obj = schema[name];
  assert.ok(obj, `${name} is not exported from the schema, so this test is not about the model`);
  const unwrap = (o) =>
    o?._def?.shape?.() ?? o?.shape ?? (o?._def?.innerType ? unwrap(o._def.innerType) : undefined) ?? (o?._def?.schema ? unwrap(o._def.schema) : undefined);
  const shape = unwrap(obj);
  assert.ok(shape, `could not read ${name}'s fields — this test would pass on nothing`);
  return Object.keys(shape);
};

/** The shapes a reviewer operates on while looking at the product. */
const REVIEWED = ["View", "Prototype", "PrototypeFile"];

test("⛔ every fact a reviewer states is reachable from where they are standing", () => {
  const unreachable = [];
  for (const name of REVIEWED)
    for (const field of shapeOf(name)) {
      if (NOT_A_REVIEWERS_FACT.has(field)) continue;
      const by = REACHED_BY.get(field);
      if (by && INTENTS.some((i) => i.name === by)) continue;
      if (FIELDS_INTENTS_TAKE.has(field.toLowerCase())) continue;
      unreachable.push(
        `${name}.${field} — no intent sets it, so the only way to state it is to hand-edit a document`
      );
    }
  assert.deepEqual(
    unreachable,
    [],
    `a reviewer cannot state these from the page:\n  - ${unreachable.join("\n  - ")}\n` +
      "Either give it an intent and list it in REACHED_BY, or say in NOT_A_REVIEWERS_FACT why no reviewer sets it."
  );
});

test("⛔ every intent REACHED_BY names actually exists", () => {
  /**
   * The list above is the load-bearing half, so it cannot be allowed to name an intent that was
   * renamed or removed — that would be a claim of reachability with nothing behind it, which is the
   * failure this file is about, written into the file about it.
   */
  const missing = [...REACHED_BY.entries()]
    .filter(([, intent]) => !INTENTS.some((i) => i.name === intent))
    .map(([field, intent]) => `${field} claims to be reachable by "${intent}", which is not an intent`);
  assert.deepEqual(missing, [], missing.join("\n"));
});

test("⛔ the reviewer's intents are on the author gate, never consent", () => {
  /**
   * Stating where a prototype sits, or which screen holds which, is somebody writing product truth.
   * It is not agreement to it. An intent that minted consent here would have the page quietly
   * stamping truth as a side effect of being tidied — the one thing tenet 1 is about.
   */
  for (const name of new Set(REACHED_BY.values())) {
    const intent = INTENTS.find((i) => i.name === name);
    assert.ok(intent, `${name} is not an intent`);
    assert.equal(intent.gate, "author", `${name} is on the ${intent.gate} gate — writing truth is not agreeing to it`);
  }
});

test("⛔ and the claim is falsifiable — removing an intent fails it", () => {
  /**
   * The test above passes by finding intents. If `REVIEWED` were empty, or a shape unreadable, it
   * would pass by checking nothing — so this asserts the machinery actually reached fields and found
   * them through the intents rather than through the exemption list.
   */
  const fields = REVIEWED.flatMap((n) => shapeOf(n));
  assert.ok(fields.length > 10, `only ${fields.length} fields walked — the shapes are not being read`);
  const throughIntents = fields.filter((f) => REACHED_BY.has(f) || FIELDS_INTENTS_TAKE.has(f.toLowerCase()));
  assert.ok(
    throughIntents.length >= REACHED_BY.size,
    "no field was reached through an intent, so this file is passing on its exemption list alone"
  );
});
